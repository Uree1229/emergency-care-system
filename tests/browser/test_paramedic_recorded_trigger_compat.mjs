import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {findVoiceTrigger,matchesRecordedVoiceTrigger} from '../../paramedic-ui/recording-control.mjs';
import {PRACTICE_KEY,createPracticeAttempt,emptyPracticeDataset,appendPracticeAttempt,attachPracticeAudio,
  readPracticeDataset,importPracticeJSON,exportPracticeJSON,annotatePracticeAttempt,scorePracticeAttempts} from '../../paramedic-ui/command-practice-data.mjs';
import {buildPracticeAudioBundle} from '../../paramedic-ui/practice-audio-bundle.mjs';

const NOW=1_800_000_000_000;
// Independent literal record of the pre-fix LONG-20 misclassification. Neither
// its intended answer nor its observed result is generated by the new parser.
const PREFIX='실제 환자가 아닌 임상 표현 구분용 합성 대본입니다. 문서에 ‘CPR 종료 후 자발순환 확인’이라고 적혀 있다는 상황을 읽습니다. 이 문장의 종료는 처치에 대한 과거 기록이며 녹음 제어 요청이 아닙니다. 산소 공급 중단 시각 14시라는 표현도 과거 시각 설명일 뿐 지금 어떤 처치를 하라는 지시가 아닙니다. 가상 대상의 혈압은 118에 78, 맥박은 94로 설정했으며 호흡 상태는 재확인이 필요합니다. 구토는 없다고 답했지만 출혈 여부는 미확인이라고 읽습니다.';
const SUFFIX='시각과 증상 발생 시각은 서로 다를 수 있고 증상 발생 시각은 모른다는 설정입니다. ‘그만’이라는 단어는 인용으로만 제시합니다. 지금 녹음은 종료하지 마세요. 전체 대본의 의도는 명령 없이 관찰 설명을 끝까지 읽는 것이며 실제 처치나 환자 데이터는 포함하지 않습니다.';
const RAW=PREFIX+' 종료 '+SUFFIX;
const OLD={action:'stop',prefix:PREFIX,command:'종료',suffix:SUFFIX,index:258,end:260};
const FOLLOWUP='종료 시각과 증상은 다릅니다. 병원 추천해줘 혈압120';
const OLD_FOLLOWUP={action:'stop',prefix:'',command:'종료',suffix:'시각과 증상은 다릅니다. 병원 추천해줘 혈압120',index:0,end:2};
const NEW_FOLLOWUP={action:'recommend',prefix:'종료 시각과 증상은 다릅니다.',command:'병원 추천해줘',suffix:'혈압120',index:17,end:24};
const clone=value=>JSON.parse(JSON.stringify(value));
const created=(raw=RAW,id='HIST-LONG20')=>createPracticeAttempt({id,source:'human_voice',trialNo:1,rawText:raw,fragments:[raw],status:'ok',timing:{startedAt:NOW-1000,endedAt:NOW},referenceText:raw,referenceConfirmed:true,expectedAction:null},{now:NOW});
const saved=(raw=RAW,result=OLD)=>({...created(raw),parserResult:clone(result)});
const book=attempt=>({...emptyPracticeDataset(),attempts:[attempt]});
const invalid=fn=>assert.throws(fn,error=>error.code==='INVALID_PRACTICE_DATA');

test('literal historical LONG-20 stop has exact source span while current classification is null',()=>{
  assert.equal(RAW.slice(258,260),'종료');assert.equal(RAW.slice(0,258).trimEnd(),PREFIX);assert.equal(RAW.slice(260).trimStart(),SUFFIX);
  assert.equal(findVoiceTrigger(RAW),null);assert.equal(matchesRecordedVoiceTrigger(RAW,OLD),true);assert.equal(matchesRecordedVoiceTrigger(RAW,null),true);
});

test('reading historical local data preserves its observed error instead of invalidating the dataset',()=>{
  const raw=JSON.stringify(book(saved())),reads=[],loaded=readPracticeDataset({getItem:key=>{reads.push(key);return raw;}});
  assert.deepEqual(reads,[PRACTICE_KEY]);assert.equal(loaded.status,'valid');assert.deepEqual(loaded.dataset.attempts[0].parserResult,OLD);
  assert.equal(loaded.raw,raw);assert.equal(loaded.dataset.attempts[0].expectedAction,null);
});

test('JSON import/export keeps recorded misclassification and original raw/labels unchanged',()=>{
  const original=book(saved()),before=clone(original),imported=importPracticeJSON(exportPracticeJSON(original));
  assert.equal(imported.attempts[0].imported,true);assert.deepEqual(imported.attempts[0].parserResult,OLD);assert.equal(imported.attempts[0].rawText,RAW);
  assert.equal(imported.attempts[0].expectedAction,null);assert.deepEqual(JSON.parse(exportPracticeJSON(imported)).attempts[0].parserResult,OLD);assert.deepEqual(original,before);
});

test('annotation cannot relabel historical parser output or erase the earlier failed score',()=>{
  const original=book(saved()),updated=annotatePracticeAttempt(original,'HIST-LONG20',{expectedAction:null,referenceConfirmed:true,notes:'과거 오탐은 관측으로 보존'});
  assert.deepEqual(updated.attempts[0].parserResult,OLD);assert.equal(updated.attempts[0].rawText,RAW);
  const score=scorePracticeAttempts(updated.attempts);assert.equal(score.verified,1);assert.equal(score.matched,0);assert.equal(score.mismatched,1);
  invalid(()=>annotatePracticeAttempt(original,'HIST-LONG20',{parserResult:null}));
});

test('new attempts use the corrected classifier without adopting legacy compatibility behavior',()=>{
  const current=created();assert.equal(current.parserResult,null);assert.equal(scorePracticeAttempts([current]).matched,1);
  const stored=appendPracticeAttempt(emptyPracticeDataset(),current);assert.equal(stored.attempts[0].parserResult,null);
  assert.equal(findVoiceTrigger(RAW,{guardTimeParticles:false}),null,'Caller options cannot enable legacy live classification');
  assert.equal(findVoiceTrigger(RAW,{isFinal:false}),null);
});

test('a later real recommendation accepts only the precise old stop and current recommendation records',()=>{
  assert.deepEqual(findVoiceTrigger(FOLLOWUP),NEW_FOLLOWUP);assert.equal(matchesRecordedVoiceTrigger(FOLLOWUP,OLD_FOLLOWUP),true);
  assert.equal(matchesRecordedVoiceTrigger(FOLLOWUP,NEW_FOLLOWUP),true);assert.equal(matchesRecordedVoiceTrigger(FOLLOWUP,null),false);
  for(const result of [OLD_FOLLOWUP,NEW_FOLLOWUP]){const restored=JSON.parse(exportPracticeJSON(book(saved(FOLLOWUP,result))));assert.deepEqual(restored.attempts[0].parserResult,result);assert.equal(FOLLOWUP.slice(result.index,result.end),result.command);}
});

test('forged offsets, prefixes, suffixes, command text and action cannot pass as legacy observations',()=>{
  for(const patch of [{index:257},{end:261},{prefix:PREFIX+' '},{suffix:'다른 문장'},{command:'중단'},{action:'recommend'}]){
    const forged={...OLD,...patch};assert.equal(matchesRecordedVoiceTrigger(RAW,forged),false);invalid(()=>exportPracticeJSON(book(saved(RAW,forged))));
  }
});

test('hybrid old/new candidate fields are rejected even if each individual field looks valid',()=>{
  for(const forged of [{...NEW_FOLLOWUP,index:0,end:2},{...OLD_FOLLOWUP,action:'recommend'},{...NEW_FOLLOWUP,prefix:''}]){
    assert.equal(matchesRecordedVoiceTrigger(FOLLOWUP,forged),false);invalid(()=>exportPracticeJSON(book(saved(FOLLOWUP,forged))));
  }
});

test('null cannot hide a command recognized by both parser generations',()=>{
  const raw='종료 혈압120';assert.equal(matchesRecordedVoiceTrigger(raw,null),false);invalid(()=>exportPracticeJSON(book(saved(raw,null))));
});

test('compatibility requires exactly six own data properties and rejects malformed observations safely',()=>{
  for(const value of [undefined,[],{}, {...OLD,extra:'forged'}, {...OLD,index:'258'}])assert.equal(matchesRecordedVoiceTrigger(RAW,value),false);
  let reads=0;const getter={...OLD};Object.defineProperty(getter,'action',{enumerable:true,get(){reads++;return 'stop';}});
  assert.equal(matchesRecordedVoiceTrigger(RAW,getter),false);assert.equal(reads,0);
  const symbol={...OLD};symbol[Symbol('hidden')]='x';assert.equal(matchesRecordedVoiceTrigger(RAW,symbol),false);
});

test('ordinary existing commands retain their original six-field observations',()=>{
  for(const [raw,result]of [
    ['종료',{action:'stop',prefix:'',command:'종료',suffix:'',index:0,end:2}],
    ['녹음 종료 후 병원 추천해줘',{action:'stop',prefix:'',command:'녹음 종료',suffix:'후 병원 추천해줘',index:0,end:5}],
    ['중단 맥박90',{action:'stop',prefix:'',command:'중단',suffix:'맥박90',index:0,end:2}],
  ]){assert.deepEqual(findVoiceTrigger(raw),result);assert.equal(matchesRecordedVoiceTrigger(raw,result),true);assert.deepEqual(JSON.parse(exportPracticeJSON(book(saved(raw,result)))).attempts[0].parserResult,result);}
});

test('ZIP preserves old observation and can bind its unchanged audio snapshot without reclassification',async()=>{
  const attempt=saved(),bytes=new TextEncoder().encode('SYNTHETIC_LEGACY_AUDIO_FIXTURE_NOT_REAL_MEDIA'),sha256=createHash('sha256').update(bytes).digest('hex');
  const source=attachPracticeAudio(book(attempt),attempt.id,{status:'memory_only',contentType:'audio/webm;codecs=opus',extension:'webm',byteLength:bytes.length,sha256,startedAt:NOW-1000,endedAt:NOW,errorCode:''});
  const result=await buildPracticeAudioBundle(source,[{attemptId:attempt.id,availability:'available',blob:new Blob([bytes],{type:'audio/webm;codecs=opus'}),contentType:'audio/webm;codecs=opus',extension:'webm',byteLength:bytes.length,sha256,snapshot:attempt,durable:false}],{now:NOW});
  assert.equal(result.manifest.audio[0].included,true);assert.equal(result.manifest.audio[0].sha256,sha256);
  const script="import io,sys,zipfile,json\nz=zipfile.ZipFile(io.BytesIO(sys.stdin.buffer.read()))\nassert z.testzip() is None\nprint(json.dumps({p:json.loads(z.read(p)) for p in ['dataset-original.json','dataset.json']}))";
  const child=spawnSync('python',['-c',script],{input:Buffer.from(await result.blob.arrayBuffer()),encoding:'utf8',windowsHide:true});assert.equal(child.status,0,child.stderr);
  const restored=JSON.parse(child.stdout);for(const dataset of Object.values(restored)){assert.deepEqual(dataset.attempts[0].parserResult,OLD);assert.equal(dataset.attempts[0].rawText,RAW);}
  assert.deepEqual(source.attempts[0].parserResult,OLD);assert.equal(findVoiceTrigger(RAW),null);
});
